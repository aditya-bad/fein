#!/usr/bin/env python3
"""Calibration scoreboard for forward paper calls: Brier + log loss, ours vs the stated base rates.

    python3 tools/scoreboard/scoreboard.py                     # from memdb -> scoreboard.md + curriculum block
    python3 tools/scoreboard/scoreboard.py --seed memdb/seeds/2027-02-01_scoreboard_resolutions.json   # preview
    python3 tools/scoreboard/scoreboard.py --no-curriculum      # do not touch memory/curriculum.md

Scored = status "resolved" with data.outcome 0/1. Void calls are counted, never scored (scoring protocol).
Brier = (p - o)^2 (lower is better; always-0.5 scores 0.25). Log loss = -ln(p_o), p clipped to [0.01, 0.99].
Skill vs base = 1 - Brier(ours)/Brier(base) on calls that have a stated base rate (>0 = we beat the naive
base-rate forecaster; the phase-B gate needs >=50 resolved and clearly positive skill).
Groups: overall, method, market, sector, batch. Calibration: 10 equal-width probability bins.
Writes research_notes/Scoreboard/scoreboard.md, appends research_notes/Scoreboard/history.csv, and rewrites
ONLY the block between <!-- SCOREBOARD:START --> and <!-- SCOREBOARD:END --> in memory/curriculum.md
(markers are added after the existing Scoreboard table if absent; nothing else in the file changes).
"""
from __future__ import annotations

import argparse
import collections
import csv
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sb_common as C  # noqa: E402

START, END = "<!-- SCOREBOARD:START -->", "<!-- SCOREBOARD:END -->"
GROUPS = ["method", "market", "sector", "batch"]


def fmt(x, nd=3):
    return "–" if x is None else f"{x:.{nd}f}"


def scored(calls):
    return [c for c in calls if c["status"] == "resolved" and c.get("outcome") in (0, 1)]


def metrics(calls) -> dict:
    """calls: normalised dicts with probability, base_rate_probability, outcome (0/1)."""
    n = len(calls)
    if not n:
        return {"n": 0}
    o = [c["outcome"] for c in calls]
    p = [c["probability"] for c in calls]
    paired = [c for c in calls if c.get("base_rate_probability") is not None]
    out = {"n": n, "n_base": len(paired), "brier": sum(C.brier(a, b) for a, b in zip(p, o)) / n,
           "logloss": sum(C.logloss(a, b) for a, b in zip(p, o)) / n, "hit_rate": sum(o) / n,
           "mean_p": sum(p) / n}
    if paired:
        bo = sum(C.brier(c["probability"], c["outcome"]) for c in paired) / len(paired)
        bb = sum(C.brier(c["base_rate_probability"], c["outcome"]) for c in paired) / len(paired)
        out.update(brier_paired=bo, brier_base=bb,
                   logloss_paired=sum(C.logloss(c["probability"], c["outcome"]) for c in paired) / len(paired),
                   logloss_base=sum(C.logloss(c["base_rate_probability"], c["outcome"]) for c in paired) / len(paired),
                   skill=(1 - bo / bb) if bb > 0 else None,
                   wins=sum(C.brier(c["probability"], c["outcome"]) < C.brier(c["base_rate_probability"], c["outcome"])
                            for c in paired),
                   ties=sum(abs(C.brier(c["probability"], c["outcome"]) - C.brier(c["base_rate_probability"], c["outcome"]))
                            < 1e-12 for c in paired))
    return out


def by_group(calls, key):
    g = collections.defaultdict(list)
    for c in calls:
        g[c.get(key) or "unknown"].append(c)
    return {k: metrics(v) for k, v in sorted(g.items())}


def calibration(calls, field="probability", bins=10):
    rows = []
    for i in range(bins):
        lo, hi = i / bins, (i + 1) / bins
        inb = [c for c in calls if c.get(field) is not None and
               (lo <= c[field] < hi or (i == bins - 1 and c[field] == 1.0))]
        rows.append({"bin": f"{lo:.1f}–{hi:.1f}", "n": len(inb),
                     "mean_p": sum(c[field] for c in inb) / len(inb) if inb else None,
                     "observed": sum(c["outcome"] for c in inb) / len(inb) if inb else None})
    return rows


def metric_table(groups: dict, label: str) -> list[str]:
    out = [f"| {label} | n | Brier ours | Brier base (paired) | Skill vs base | Log loss ours / base | Ours better |",
           "|---|---|---|---|---|---|---|"]
    for k, m in groups.items():
        if not m.get("n"):
            continue
        out.append(f"| {k} | {m['n']} | {fmt(m['brier'])} | {fmt(m.get('brier_base'))} | {fmt(m.get('skill'), 2)} | "
                   f"{fmt(m['logloss'])} / {fmt(m.get('logloss_base'))} | "
                   f"{m.get('wins', '–')}/{m.get('n_base', 0)} |")
    return out


def build_report(calls, today, rows_calls=None) -> tuple[str, dict]:
    sc = scored(calls)
    void = [c for c in calls if c["status"] == "void"]
    opn = [c for c in calls if c["status"] == "open"]
    m = metrics(sc)
    L = [f"# Paper-call scoreboard (as of {today})", "",
         "Generated by `tools/scoreboard/scoreboard.py` from memdb (`--tag paper-call`). Stage 7 of the roadmap. "
         "Forward calls test *methods*, not stocks; they are not recommendations.", "",
         f"**Resolved & scored:** {len(sc)} · **void:** {len(void)} · **open:** {len(opn)} · "
         f"**gate to phase B:** ≥50 resolved with clearly positive skill vs base → "
         f"{len(sc)}/50 resolved" + (f", skill {fmt(m.get('skill'), 2)}" if m.get("skill") is not None else ""), "",
         "Brier = (p − outcome)², lower is better (always-50% = 0.250). Skill vs base = 1 − Brier(ours)/Brier(base) "
         "on calls with a stated base rate. Log loss clips p to [0.01, 0.99]. Small n is noise: read method-level "
         "numbers only once a method has ≥5 resolved calls (batch2.md protocol).", ""]
    L += ["## Overall", ""] + metric_table({"all": m}, "Set") + [""]
    for g in GROUPS:
        L += [f"## By {g}", ""] + (metric_table(by_group(sc, g), g) if sc else ["_No resolved calls yet._"]) + [""]
    L += ["## Calibration (10 bins)", "",
          "| Bin | n (ours) | mean p (ours) | observed | n (base) | mean p (base) | observed |", "|---|---|---|---|---|---|---|"]
    cb, cbb = calibration(sc), calibration(sc, "base_rate_probability")
    for a, b in zip(cb, cbb):
        L.append(f"| {a['bin']} | {a['n']} | {fmt(a['mean_p'], 2)} | {fmt(a['observed'], 2)} | {b['n']} | "
                 f"{fmt(b['mean_p'], 2)} | {fmt(b['observed'], 2)} |")
    nobase = [c["id"] for c in sc if c.get("base_rate_probability") is None]
    if nobase:
        L += ["", f"Scored without a base rate (in 'ours', excluded from skill): {len(nobase)}"]
    pm = [c for c in sc if abs(c["probability"] - c["outcome"]) > 0.6]
    L += ["", "## Post-mortems owed (|p − outcome| > 0.6)", ""]
    L += [f"- `{c['id']}` p={c['probability']} outcome={c['outcome']}" for c in pm] or ["_None._"]
    L += ["", "## Resolved calls", "", "| Call | Method | Market | P(ours) | P(base) | Outcome | Brier ours / base | Resolved on |",
          "|---|---|---|---|---|---|---|---|"]
    for c in sorted(sc, key=lambda c: c["data"].get("resolved_on", "")):
        b = c.get("base_rate_probability")
        L.append(f"| `{c['id'].replace('thesis:paper-call:', '')}` | {c['method']} | {c['market']} | {c['probability']} | "
                 f"{b if b is not None else '–'} | {c['outcome']} | {fmt(C.brier(c['probability'], c['outcome']))} / "
                 f"{fmt(C.brier(b, c['outcome']) if b is not None else None)} | {c['data'].get('resolved_on', '')} |")
    if void:
        L += ["", "## Void (not scored)", ""] + [f"- `{c['id']}`: {c['data'].get('void_reason', '')}" for c in void]
    if rows_calls is not None:
        import calls as K
        s = K.summary(rows_calls)
        L += ["", "## Open calls by resolution type", "", "| Type | Meaning | Open calls | Automation split |", "|---|---|---|---|"]
        for t in "abcd":
            split = ", ".join(f"{k.split('/')[1]} {v}" for k, v in sorted(s["by_type_auto"].items()) if k.startswith(t + "/"))
            L.append(f"| {t} | {K.TYPE_NAMES[t]} | {s['by_type'].get(t, 0)} | {split} |")
        nxt = sorted(rows_calls, key=lambda r: (r["check_from"] or r["resolve_by"], r["resolve_by"]))[:12]
        L += ["", "## Next checks", "", "| Check from | Resolve by | Call | Type |", "|---|---|---|---|"]
        L += [f"| {r['check_from']} | {r['resolve_by']} | `{r['id'].replace('thesis:paper-call:', '')}` | "
              f"{r['type']}/{r['automation']} |" for r in nxt]
        L += ["", "Full calendar: `research_notes/Scoreboard/calendar.md` (and `calendar.ics`)."]
    summary = {"as_of": str(today), "resolved": len(sc), "void": len(void), "open": len(opn), **m,
               "first_resolve_by": min((c["resolve_by"] for c in opn if c["resolve_by"]), default=None)}
    return "\n".join(L) + "\n", summary


def curriculum_block(s, groups_method, nxt_txt) -> str:
    lines = [START, f"**Auto scoreboard** — `tools/scoreboard/scoreboard.py`, updated {s['as_of']}. "
             "Generated block: do not edit inside the markers. Full: `research_notes/Scoreboard/scoreboard.md`.", "",
             "| As of | Resolved | Void | Open | Brier (ours) | Brier (base, paired) | Skill vs base | Log loss ours / base | Next |",
             "|---|---|---|---|---|---|---|---|---|",
             f"| {s['as_of']} | {s['resolved']} | {s['void']} | {s['open']} | {fmt(s.get('brier'))} | "
             f"{fmt(s.get('brier_base'))} | {fmt(s.get('skill'), 2)} | {fmt(s.get('logloss'))} / "
             f"{fmt(s.get('logloss_base'))} | {nxt_txt} |"]
    rows = [(k, m) for k, m in groups_method.items() if m.get("n")]
    if rows:
        lines += ["", "| Method | n | Brier ours | Brier base | Skill |", "|---|---|---|---|---|"]
        lines += [f"| {k} | {m['n']} | {fmt(m['brier'])} | {fmt(m.get('brier_base'))} | {fmt(m.get('skill'), 2)} |"
                  for k, m in rows]
    lines.append(END)
    return "\n".join(lines)


def update_curriculum(path, block) -> str:
    text = C.read_text(path)
    if START in text and END in text and text.index(START) < text.index(END):
        a, b = text.index(START), text.index(END) + len(END)
        new = text[:a] + block + text[b:]
    else:
        lines = text.split("\n")
        try:
            h = next(i for i, ln in enumerate(lines) if ln.strip().lower() == "## scoreboard")
        except StopIteration:
            new = text.rstrip("\n") + "\n\n## Scoreboard\n" + block + "\n"
        else:
            j = h + 1
            while j < len(lines) and not lines[j].startswith("|"):
                j += 1
            while j < len(lines) and lines[j].startswith("|"):
                j += 1
            new = "\n".join(lines[:j] + ["", block] + lines[j:])
    if new != text:
        C.write_text(path, new)
    return new


def append_history(path, s):
    rows = []
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            rows = [r for r in csv.DictReader(fh) if r["as_of"] != s["as_of"]]
    f = ["as_of", "resolved", "void", "open", "brier", "brier_base", "skill", "logloss", "logloss_base"]
    rows.append({k: (round(s[k], 6) if isinstance(s.get(k), float) else s.get(k, "")) for k in f})
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=f)
        w.writeheader()
        w.writerows(rows)


def merge_seed(calls, seed_path):
    """Preview: overlay unapplied seed records on the memdb calls."""
    recs = {r["id"]: r for r in C.read_json(seed_path)}
    out = []
    for c in calls:
        r = recs.get(c["id"])
        if r:
            c = dict(c, status=r.get("status", c["status"]), data={**c["data"], **(r.get("data") or {})})
            c["outcome"] = c["data"].get("outcome")
        out.append(c)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seed", action="append", default=[], help="overlay an unapplied resolution seed (preview)")
    ap.add_argument("--out", default=os.path.join(C.OUT_DIR, "scoreboard.md"))
    ap.add_argument("--no-curriculum", action="store_true")
    ap.add_argument("--curriculum", default=C.CURRICULUM)
    a = ap.parse_args(argv)
    calls = C.load_calls(include_closed=True)
    for s in a.seed:
        calls = merge_seed(calls, s)
    import calls as K
    rows = K.build_rows([c for c in calls if c["status"] == "open"], C.load_specs())
    today = C.today()
    md, s = build_report(calls, today, rows)
    C.write_text(a.out, md)
    append_history(os.path.join(C.OUT_DIR, "history.csv"), s)
    upcoming = sorted((r["check_from"] or r["resolve_by"], r["ticker"]) for r in rows
                      if (r["check_from"] or r["resolve_by"]) > today.isoformat())
    nxt = (f"next check {upcoming[0][0]} ({upcoming[0][1]}); earliest open resolve-by {s['first_resolve_by']}"
           if upcoming else f"earliest open resolve-by {s['first_resolve_by']}")
    if not a.no_curriculum and not a.seed:
        update_curriculum(a.curriculum, curriculum_block(s, by_group(scored(calls), "method"), nxt))
    print(f"scoreboard -> {a.out}: resolved {s['resolved']}, void {s['void']}, open {s['open']}, "
          f"Brier {fmt(s.get('brier'))} vs base {fmt(s.get('brier_base'))}; {nxt}")
    return s


if __name__ == "__main__":
    main()
