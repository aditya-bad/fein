#!/usr/bin/env python3
"""Step 3: weighted rule-vs-outcome statistics with stratified company bootstrap (reuses solvency_india
s4_analyze.stats / verdict), pre-registered verdicts, comparison with the old survivors-only Part B.
Output: research_notes/Backtests/hard_filters_india_v2_outputs/results.json, tables.md."""
import json, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common2 as C
sys.path.insert(0, os.path.join(C.ROOT, "tools", "backtests", "solvency_india"))
import s4_analyze as S4

K = C.K
# (flag, label, role, scope) ; scope 'pooled' or 'FY2018' (deviation logged: history-dependent rules)
RULES = [("A", "(a) CFO/PAT 5y < 0.3", "primary", "FY2018"),
         ("A7", "(a') CFO/PAT 5y < 0.7", "secondary", "FY2018"),
         ("B25", "(b) pledge > 25% of promoter holding", "primary", "pooled"),
         ("B50", "(b') pledge > 50%", "primary", "pooled"),
         ("B_rise", "(b'') pledge up >= 10 pp in a year", "exploratory", "pooled"),
         ("C", "(c) debt >= 1.5x in 3y with 3y CFO < 0", "primary", "FY2018"),
         ("D50", "(d) other income > 50% of PBT (3y)", "primary", "pooled"),
         ("D30", "(d') other income > 30% of PBT (3y)", "secondary", "pooled"),
         ("E", "(e) debtor days x1.5 in 3y", "primary", "FY2018"),
         ("E60", "(e') debtor days x1.5 and >= 60", "exploratory", "FY2018"),
         ("ANY", "ANY of a, b, c, d, e", "primary", "FY2018"),
         ("ANY_np", "ANY without pledge", "secondary", "FY2018"),
         ("TWO", ">= 2 of a-e", "exploratory", "FY2018")]


def scoped(rows, scope):
    return rows if scope == "pooled" else [r for r in rows if r["snap"] == scope]


def wrate(g, out):
    g = [r for r in g if r.get(out) not in ("", None)]
    w = sum(float(r["weight"]) for r in g)
    return (sum(float(r["weight"]) * float(r[out]) for r in g) / w if w else float("nan")), len(g)


def table(rows, out, title, scope_override=None, boot=True, roles=("primary", "secondary", "exploratory")):
    md = [f"### {title}", "", "| rule | scope | known | fired | fired & failed | wtd share flagged | precision | base | "
          "lift [95% CI] | recall | >=3x winners flagged | verdict |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    res = {}
    for k, lab, role, scope in RULES:
        if role not in roles:
            continue
        sc = scope_override or scope
        r = S4.stats(scoped(rows, sc), k, out, boot)
        res[k] = r
        if r is None:
            md.append(f"| {lab} | {sc} | 0 | | | | | | | | | no data |")
            continue
        v = S4.verdict(r)
        v = v if role == "primary" else f"({v})"
        md.append(f"| {lab} | {sc} | {r['n_known']} | {r['n_fired']} | {r['n_fired_fail']} | {S4.pct(r['w_fired_share'])} | "
                  f"{S4.pct(r['prec'])} | {S4.pct(r['base'])} | {S4.f2(r['lift'])} {S4.ci(r.get('lift_ci'))} | "
                  f"{S4.pct(r['recall'])} | {S4.pct(r['wexcl'])} ({r['n_fired_winners']}/{r['n_winners']}) | {v} |")
    return md + [""], res


def compare(rows, title):
    md = [f"### {title}", "", "| rule | scope | flagged n | flagged loss50 | unflagged loss50 | flagged x3 | unflagged x3 |",
          "|---|---|---|---|---|---|---|"]
    res = {}
    for k, lab, role, scope in RULES:
        if role == "exploratory":
            continue
        g = [r for r in scoped(rows, scope) if r.get(k) not in ("", None)]
        fl = [r for r in g if r[k] == "1"]
        un = [r for r in g if r[k] == "0"]
        a, n1 = wrate(fl, "loss50")
        b, _ = wrate(un, "loss50")
        c, _ = wrate(fl, "winner")
        d, _ = wrate(un, "winner")
        res[k] = dict(n_fl=len(fl), loss50_fl=a, loss50_un=b, x3_fl=c, x3_un=d)
        md.append(f"| {lab} | {scope} | {len(fl)} | {S4.pct(a)} | {S4.pct(b)} | {S4.pct(c)} | {S4.pct(d)} |")
    return md + [""], res


def main():
    rows = K.read_csv(os.path.join(C.OUT, "panel_v2.csv"))
    out = {"n_rows": len(rows)}
    md = ["# v2 hard-filter rules on the survivorship-free Indian panel — tables (generated by h3_analyze.py)", "",
          "Weighted by stratum (D census, X and L samples). Counts are unweighted rows; rates weighted. CIs: 2,000 "
          "stratified bootstrap draws by company. Scope FY2018 = history-dependent rules (logged deviation). "
          "Research, not SEBI-registered advice.", ""]
    m, res = table(rows, "o_fail", "PRIMARY — O_fail (liquidation ∨ compulsory exit ∨ price ≤ 0.2×) within 5y")
    md += m
    out["primary"] = res
    out["verdicts"] = {k: S4.verdict(res[k]) for k, _, role, _ in RULES if role == "primary" and res.get(k)}
    m, out["o_strict"] = table(rows, "o_strict", "Robustness — O_strict (liquidation ∨ compulsory exit)")
    md += m
    for sn in K.SNAPS:
        m, out[sn] = table(rows, "o_fail", f"Robustness — {sn} only (O_fail)", scope_override=sn)
        md += m
    m, out["L_only"] = table([r for r in rows if r["stratum"] == "L"], "o_fail",
                             "Robustness — live stratum L only (survivor-like slice)")
    md += m
    m, out["mcap400"] = table([r for r in rows if float(r["mcap"]) >= 400], "o_fail",
                              "Robustness — mcap ≥ ₹400 cr at T")
    md += m
    m, out["cmp_all"] = compare(rows, "Old Part B metrics on the full panel (weighted): loss50 = 5y ratio < 0.5 (or failed), x3 = 5y ratio ≥ 3")
    md += m
    m, out["cmp_L"] = compare([r for r in rows if r["stratum"] == "L"], "Same, live stratum L only (what a survivors-only universe sees)")
    md += m
    # base rates
    for sc in ("pooled", "FY2018", "FY2016"):
        g = scoped(rows, sc) if sc != "FY2016" else [r for r in rows if r["snap"] == "FY2016"]
        out["base_" + sc] = {o: wrate(g, o)[0] for o in ("o_fail", "o_strict", "loss50", "winner")}
    md += ["## Base rates (weighted)", "", "| scope | O_fail | O_strict | loss50 | x3 winner |", "|---|---|---|---|---|"]
    for sc in ("pooled", "FY2018", "FY2016"):
        b = out["base_" + sc]
        md.append(f"| {sc} | {S4.pct(b['o_fail'])} | {S4.pct(b['o_strict'])} | {S4.pct(b['loss50'])} | {S4.pct(b['winner'])} |")
    md.append("")
    # names
    md += ["## Names: flagged failures and flagged >=3x winners (primary rules, rule scope)", "",
           "| rule | failures flagged (first 15) | winners flagged (first 12) |", "|---|---|---|"]
    out["names"] = {}
    for k, lab, role, scope in RULES:
        if role != "primary":
            continue
        g = [r for r in scoped(rows, scope) if r.get(k) == "1"]
        fa = [f"{r['name'][:28]} {r['snap'][2:]}" for r in g if r["o_fail"] == "1"]
        wi = [f"{r['name'][:28]} {r['snap'][2:]} ({float(r['r5']):.1f}x)" for r in g if r["winner"] == "1"]
        out["names"][k] = {"failures": fa, "winners": wi}
        md.append(f"| {lab} | {'; '.join(fa[:15])} | {'; '.join(wi[:12])} |")
    md.append("")
    K.jsave(os.path.join(C.OUT, "results.json"), out)
    with open(os.path.join(C.OUT, "tables.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("\n".join(md))
    print(json.dumps(out["verdicts"]))


if __name__ == "__main__":
    main()
